#!/usr/bin/env python3
"""Generate BearSSL trust anchors from a pinned PEM bundle (python cryptography)."""
import argparse
from pathlib import Path
from cryptography import x509
from cryptography.hazmat.primitives.asymmetric import rsa, ec
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

def generate(source, output):
    certificates = x509.load_pem_x509_certificates(source.read_bytes())
    lines = ['/* Generated by tools/tls_roots.py. Do not edit. */']
    entries = []
    def data(name, value):
        lines.append('static const unsigned char ' + name + '[] = {')
        for i in range(0, len(value), 16):
            lines.append('    ' + ', '.join(f'0x{x:02x}' for x in value[i:i+16]) + ',')
        lines.append('};')
    for i, certificate in enumerate(certificates):
        prefix = f'root_{i}'
        data(prefix + '_dn', certificate.subject.public_bytes())
        key = certificate.public_key()
        if isinstance(key, rsa.RSAPublicKey):
            numbers = key.public_numbers()
            for name, n in [('n', numbers.n), ('e', numbers.e)]:
                data(prefix + '_' + name, n.to_bytes((n.bit_length()+7)//8, 'big'))
            value = '{BR_KEYTYPE_RSA, {.rsa = {(unsigned char*)%s_n, sizeof(%s_n), (unsigned char*)%s_e, sizeof(%s_e)}}}' % ((prefix,)*4)
        elif isinstance(key, ec.EllipticCurvePublicKey):
            curves = {'secp256r1': 'BR_EC_secp256r1', 'secp384r1': 'BR_EC_secp384r1', 'secp521r1': 'BR_EC_secp521r1'}
            data(prefix + '_q', key.public_bytes(Encoding.X962, PublicFormat.UncompressedPoint))
            value = '{BR_KEYTYPE_EC, {.ec = {%s, (unsigned char*)%s_q, sizeof(%s_q)}}}' % (curves[key.curve.name], prefix, prefix)
        else:
            raise ValueError('Unsupported trust-anchor key')
        entries.append('{{(unsigned char*)%s_dn, sizeof(%s_dn)}, BR_X509_TA_CA, %s}' % (prefix, prefix, value))
    lines.append('static const br_x509_trust_anchor trust_anchors[] = {')
    lines.extend('    ' + entry + ',' for entry in entries)
    lines.append('};\n')
    output.write_text('\n'.join(lines))

if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('source', type=Path)
    p.add_argument('output', type=Path)
    a = p.parse_args()
    generate(a.source, a.output)
